// Embeds the local app's files into training/ui/assets.mjs so `w3bs-training` works as a single
// compiled binary (bun build --compile) with no files beside it. `--check` exits 1 on drift.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const assets = {
  INDEX_HTML: readFileSync(here('./public/index.html'), 'utf8'),
  LOCKED_HTML: readFileSync(here('./public/locked.html'), 'utf8'),
  APP_JS: readFileSync(here('./public/app.js'), 'utf8'),
  // The W3BS colour tokens first, then the app's own styles.
  APP_CSS: readFileSync(here('../../public/tokens.css'), 'utf8') + readFileSync(here('./public/app.css'), 'utf8'),
  MARK_SVG: readFileSync(here('../../public/mark.svg'), 'utf8'),
};
const body =
  '// Generated by training/ui/build-assets.mjs from training/ui/public and public/. Do not edit.\n' +
  Object.entries(assets)
    .map(([name, text]) => `export const ${name} = ${JSON.stringify(text)};\n`)
    .join('');
const out = here('./assets.mjs');
if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== body) {
    process.stderr.write('training/ui/assets.mjs is stale. Run bun training/ui/build-assets.mjs\n');
    process.exit(1);
  }
  process.stdout.write('Training UI assets are current.\n');
} else {
  writeFileSync(out, body);
  process.stdout.write(`Wrote ${out}\n`);
}
